WITH TEMP2 AS
(WITH TEMP AS
(SELECT FISCAL_YEAR,SUM(SALE) AS CURR_YEAR_SALES FROM SALES GROUP BY FISCAL_YEAR)
SELECT *,LAG(CURR_YEAR_SALES) OVER() AS PREV_SALES FROM TEMP)
SELECT *,((CURR_YEAR_SALES-PREV_SALES)/PREV_SALES)*100 AS GROWTH_PERCTENTAGE FROM TEMP2;










