-- WINDOW FUNCTIONS
 -- AGGREGATE FUNCTIONS
SELECT FIRST_NAME,AVG(SALARY) OVER() FROM MYEMP;
SELECT FIRST_NAME,DEP_ID,AVG(SALARY) OVER() FROM MYEMP;
SELECT FIRST_NAME,DEP_ID,AVG(SALARY) OVER(PARTITION BY DEP_ID) FROM MYEMP;
SELECT *,COUNT(EMP_ID) OVER(PARTITION BY DEP_ID) AS EMP_FROM_EACH_DEP FROM MYEMP; 
 
-- RANKING
  -- RANK
SELECT * , RANK() OVER() FROM MYEMP;
SELECT * , RANK() OVER(ORDER BY SALARY DESC) FROM MYEMP;
SELECT * , RANK() OVER(PARTITION BY DEP_ID ORDER BY SALARY DESC) FROM MYEMP;
 -- DENSE RANK
SELECT * , DENSE_RANK() OVER(ORDER BY SALARY DESC) FROM MYEMP;
SELECT * , DENSE_RANK() OVER(PARTITION BY DEP_ID ORDER BY SALARY DESC) FROM MYEMP;
 -- ROW NUMBER
SELECT * , ROW_NUMBER() OVER(ORDER BY SALARY DESC) FROM MYEMP;
SELECT * , ROW_NUMBER() OVER(PARTITION BY DEP_ID ORDER BY SALARY DESC) FROM MYEMP;
 -- NTILE
SELECT *, NTILE(5) OVER() FROM MYEMP;
SELECT *, NTILE(3) OVER(ORDER BY SALARY DESC) FROM MYEMP;
SELECT *, NTILE(3) OVER(PARTITION BY DEP_ID ORDER BY SALARY DESC) FROM MYEMP;

-- ANALYTICAL/OFFSET/VALUE FUNCTIONS
 -- FIRST VALUE 
SELECT *, FIRST_VALUE(FIRST_NAME) OVER() FROM MYEMP;
SELECT *, FIRST_VALUE(FIRST_NAME) OVER(PARTITION BY DEP_ID) AS FIRST_NAME_FROM_EACH_DEPT FROM MYEMP;
SELECT *, FIRST_VALUE(FIRST_NAME) OVER(PARTITION BY DEP_ID ORDER BY SALARY DESC) AS FIRST_NAME_FROM_EACH_DEPT FROM MYEMP;
 -- LAST VALUE 
SELECT *, LAST_VALUE(FIRST_NAME) OVER() FROM MYEMP;
SELECT *, LAST_VALUE(FIRST_NAME) OVER(PARTITION BY DEP_ID) AS FIRST_NAME_FROM_EACH_DEPT FROM MYEMP;
SELECT *, LAST_VALUE(FIRST_NAME) OVER(PARTITION BY DEP_ID ORDER BY SALARY DESC) AS FIRST_NAME_FROM_EACH_DEPT FROM MYEMP;
 -- NTH VALUE 
SELECT *, NTH_VALUE(SALARY,3) OVER() FROM MYEMP;
SELECT *, NTH_VALUE(SALARY,3) OVER(PARTITION BY DEP_ID) AS FIRST_NAME_FROM_EACH_DEPT FROM MYEMP;
SELECT *, NTH_VALUE(SALARY,3) OVER(PARTITION BY DEP_ID ORDER BY SALARY DESC) AS FIRST_NAME_FROM_EACH_DEPT FROM MYEMP;
 -- LEAD
SELECT * FROM SALES;
